import { Kysely, sql } from 'kysely';
import { dedent } from 'ts-dedent';
import { DatabaseMetadata } from '../../introspector/metadata/database-metadata';
import { KyselyBunSqliteDialect } from '../dialects/kysely-bun-sqlite/kysely-bun-sqlite-dialect';
import { LibsqlDialect } from '../dialects/libsql/libsql-dialect';
import { SqliteDialect } from '../dialects/sqlite/sqlite-dialect';
import { WorkerBunSqliteDialect } from '../dialects/worker-bun-sqlite/worker-bun-sqlite-dialect';
import { generate, serializeFromMetadata } from './generate';

for (const { connectionString, dialect } of [
  { connectionString: ':memory:', dialect: new SqliteDialect() },
  { connectionString: 'file::memory:', dialect: new LibsqlDialect() },
]) {
  describe(dialect.constructor.name, () => {
    it('should generate numeric types for SQLite numeric declarations', async () => {
      const db = new Kysely({
        dialect: await dialect.createKyselyDialect({ connectionString }),
      });

      try {
        await sql`
          create table t (
            a INT, b BIGINT, d DOUBLE, e FLOAT, f DECIMAL(10,2),
            g TINYINT, t2 SMALLINT, c VARCHAR(10), w
          )
        `.execute(db);
        await sql`
          insert into t values (1, 2, 3.5, 4.5, 5.25, 6, 7, 'x', 8)
        `.execute(db);

        const { rows } = await sql`select * from t`.execute(db);
        expect(rows).toStrictEqual([
          { a: 1, b: 2, c: 'x', d: 3.5, e: 4.5, f: 5.25, g: 6, t2: 7, w: 8 },
        ]);
        expect(
          await generate({
            db,
            dialect,
            outFile: null,
            skipAutogeneratedFileComment: true,
          }),
        ).toBe(
          dedent`
            export interface T {
              a: number | null;
              b: number | null;
              c: string | null;
              d: number | null;
              e: number | null;
              f: number | null;
              g: number | null;
              t2: number | null;
              w: string | null;
            }

            export interface DB {
              t: T;
            }
          ` + '\n',
        );
      } finally {
        await db.destroy();
      }
    });
  });
}

for (const dialect of [
  new SqliteDialect(),
  new LibsqlDialect(),
  new KyselyBunSqliteDialect(),
  new WorkerBunSqliteDialect(),
]) {
  describe(`${dialect.constructor.name} serialization`, () => {
    it('should recognize numeric aliases without changing other declarations', () => {
      const dataTypes = [
        ['INT2', 'number'],
        ['int8', 'number'],
        ['MEDIUMINT', 'number'],
        ['UNSIGNED BIG INT', 'number'],
        ['DOUBLE PRECISION', 'number'],
        ['decimal', 'number'],
        ['DeCiMaL (12, 4)', 'number'],
        [' NUMERIC (+8, -2) ', 'number'],
        ['INTEGER', 'number'],
        ['REAL', 'number'],
        ['BOOLEAN', 'number'],
        ['ANY', 'unknown'],
        ['BLOB', 'Buffer'],
        ['TEXT', 'string'],
        ['DATE', 'string'],
        ['DATETIME', 'string'],
        ['STRING', 'string'],
        ['', 'string'],
        ['FLOATING POINT', 'string'],
      ] as const;
      const output = serializeFromMetadata({
        dialect,
        metadata: new DatabaseMetadata({
          tables: [
            {
              columns: dataTypes.map(([dataType], index) => ({
                dataType,
                name: `column_${index}`,
              })),
              name: 't',
            },
          ],
        }),
        skipAutogeneratedFileComment: true,
      });

      for (const [index, [, type]] of dataTypes.entries()) {
        expect(output).toContain(`  column_${index}: ${type};\n`);
      }
    });

    it('should preserve wrappers and give overrides priority over type mappings', () => {
      const metadata = new DatabaseMetadata({
        tables: [
          {
            columns: [
              { dataType: 'INT', isAutoIncrementing: true, name: 'id' },
              {
                dataType: 'DECIMAL(10,2)',
                hasDefaultValue: true,
                isNullable: true,
                name: 'amount',
              },
              { dataType: 'INT', isNullable: true, name: 'overridden' },
            ],
            name: 't',
          },
        ],
      });
      const output = serializeFromMetadata({
        customImports: { Decimal: './types' },
        dialect,
        metadata,
        overrides: { columns: { 't.overridden': '"override"' } },
        skipAutogeneratedFileComment: true,
        typeMapping: { 'decimal(10,2)': 'Decimal', int: 'bigint' },
      });

      expect(output).toContain('import type { Decimal } from "./types";\n');
      expect(output).toContain('  amount: Generated<Decimal | null>;\n');
      expect(output).toContain('  id: Generated<bigint>;\n');
      expect(output).toContain('  overridden: "override";\n');

      const defaultOutput = serializeFromMetadata({ dialect, metadata });
      expect(defaultOutput).toContain('  amount: Generated<number | null>;\n');
      expect(defaultOutput).toContain('  id: Generated<number>;\n');
      expect(defaultOutput).toContain('  overridden: number | null;\n');
    });
  });
}
